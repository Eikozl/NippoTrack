CREATE TABLE goals (
  id_goal INT NOT NULL AUTO_INCREMENT,
  title VARCHAR(120) NOT NULL,
  goal_type VARCHAR(30) NOT NULL,
  target_value INT NOT NULL,
  period_type VARCHAR(20) NOT NULL,
  target_jlpt_level VARCHAR(2) DEFAULT NULL,
  target_status VARCHAR(20) DEFAULT NULL,
  start_date DATE NOT NULL,
  due_date DATE DEFAULT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id_goal),
  KEY idx_goals_active_due (is_active, due_date),
  KEY idx_goals_type_period (goal_type, period_type),
  CONSTRAINT chk_goals_type CHECK (goal_type IN ('study_minutes', 'vocabulary_count', 'kanji_count', 'grammar_count')),
  CONSTRAINT chk_goals_target_value CHECK (target_value > 0),
  CONSTRAINT chk_goals_period CHECK (period_type IN ('weekly', 'cumulative', 'by_deadline')),
  CONSTRAINT chk_goals_jlpt CHECK (target_jlpt_level IN ('N5', 'N4', 'N3', 'N2', 'N1') OR target_jlpt_level IS NULL),
  CONSTRAINT chk_goals_status CHECK (target_status IN ('New', 'Learning', 'Familiar', 'Mastered') OR target_status IS NULL),
  CONSTRAINT chk_goals_dates CHECK (due_date IS NULL OR due_date >= start_date),
  CONSTRAINT chk_goals_active CHECK (is_active IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
