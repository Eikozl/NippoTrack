-- Immutable, user-owned evidence that a learned kanji was encountered in JLT.
-- Express with jlt_runtime is the only normal runtime database boundary.
CREATE TABLE IF NOT EXISTS kanji_encounters (
  id_kanji_encounter integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE RESTRICT,
  id_kanji integer NOT NULL REFERENCES kanji (id_kanji) ON DELETE CASCADE,
  source_type varchar(40) NOT NULL,
  source_id integer,
  encountered_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  dedupe_key varchar(255) NOT NULL,
  CONSTRAINT chk_kanji_encounters_source_type CHECK (source_type IN ('vocabulary', 'session_writing')),
  CONSTRAINT chk_kanji_encounters_source_id CHECK (source_id IS NULL OR source_id > 0),
  CONSTRAINT kanji_encounters_user_dedupe_key UNIQUE (user_id, dedupe_key)
);

CREATE INDEX IF NOT EXISTS idx_kanji_encounters_user_kanji_time
  ON kanji_encounters (user_id, id_kanji, encountered_at DESC);

CREATE INDEX IF NOT EXISTS idx_kanji_encounters_user_source
  ON kanji_encounters (user_id, source_type, source_id);

ALTER TABLE kanji_encounters ENABLE ROW LEVEL SECURITY;
ALTER TABLE kanji_encounters FORCE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE kanji_encounters FROM PUBLIC;
REVOKE ALL PRIVILEGES ON TABLE kanji_encounters FROM anon, authenticated;
GRANT SELECT, INSERT ON TABLE kanji_encounters TO jlt_runtime;
GRANT USAGE, SELECT ON SEQUENCE kanji_encounters_id_kanji_encounter_seq TO jlt_runtime;

DROP POLICY IF EXISTS kanji_encounters_runtime_select ON kanji_encounters;
CREATE POLICY kanji_encounters_runtime_select
  ON kanji_encounters
  FOR SELECT
  TO jlt_runtime
  USING (true);

DROP POLICY IF EXISTS kanji_encounters_runtime_insert ON kanji_encounters;
CREATE POLICY kanji_encounters_runtime_insert
  ON kanji_encounters
  FOR INSERT
  TO jlt_runtime
  WITH CHECK (true);
