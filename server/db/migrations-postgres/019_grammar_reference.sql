CREATE TABLE IF NOT EXISTS grammar_reference (
  id_grammar_reference integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_key text NOT NULL UNIQUE,
  grammar_point text NOT NULL,
  kana text,
  romaji text,
  meaning text NOT NULL,
  summary text,
  structures jsonb NOT NULL DEFAULT '[]'::jsonb,
  pitfalls jsonb NOT NULL DEFAULT '[]'::jsonb,
  examples jsonb NOT NULL DEFAULT '[]'::jsonb,
  jlpt_level varchar(2) NOT NULL,
  source text NOT NULL,
  source_slug text NOT NULL,
  source_commit char(40) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_grammar_reference_jlpt CHECK (jlpt_level IN ('N5', 'N4', 'N3', 'N2', 'N1')),
  CONSTRAINT uq_grammar_reference_source_identity UNIQUE (source, source_slug, source_commit)
);

ALTER TABLE grammar_points ADD COLUMN IF NOT EXISTS reference_id integer;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'grammar_points_reference_id_fkey') THEN
    ALTER TABLE grammar_points ADD CONSTRAINT grammar_points_reference_id_fkey
      FOREIGN KEY (reference_id) REFERENCES grammar_reference (id_grammar_reference) ON DELETE SET NULL;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_grammar_points_reference_id ON grammar_points (reference_id);
CREATE INDEX IF NOT EXISTS idx_grammar_reference_search ON grammar_reference (jlpt_level, grammar_point);

-- Conservative legacy linkage: exact canonical title only and only when it is unique.
UPDATE grammar_points g SET reference_id = reference_row.id_grammar_reference
FROM (
  SELECT lower(trim(grammar_point)) AS key, min(id_grammar_reference) AS id_grammar_reference
  FROM grammar_reference GROUP BY lower(trim(grammar_point)) HAVING count(*) = 1
) reference_row
WHERE g.reference_id IS NULL AND lower(trim(g.grammar_point)) = reference_row.key;

