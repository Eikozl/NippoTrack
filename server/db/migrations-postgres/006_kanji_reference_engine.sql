-- Shared, backend-managed kanji metadata. Normal application traffic can only
-- read this table; imports use the separate migration/admin connection.
CREATE TABLE IF NOT EXISTS kanji_reference (
  id_kanji_reference integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  character text NOT NULL UNIQUE,
  jlpt_level varchar(2),
  onyomi text[] NOT NULL DEFAULT ARRAY[]::text[],
  kunyomi text[] NOT NULL DEFAULT ARRAY[]::text[],
  meanings text[] NOT NULL DEFAULT ARRAY[]::text[],
  stroke_count smallint,
  source_metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_kanji_reference_character_length CHECK (char_length(character) = 1),
  CONSTRAINT chk_kanji_reference_jlpt CHECK (jlpt_level IN ('N5', 'N4', 'N3', 'N2', 'N1') OR jlpt_level IS NULL),
  CONSTRAINT chk_kanji_reference_stroke_count CHECK (stroke_count IS NULL OR stroke_count > 0)
);

ALTER TABLE kanji ADD COLUMN IF NOT EXISTS reference_id integer;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'kanji_reference_id_fkey'
      AND conrelid = 'public.kanji'::regclass
  ) THEN
    ALTER TABLE kanji
      ADD CONSTRAINT kanji_reference_id_fkey
      FOREIGN KEY (reference_id)
      REFERENCES kanji_reference (id_kanji_reference)
      ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_kanji_reference_id ON kanji (reference_id);

ALTER TABLE kanji_reference ENABLE ROW LEVEL SECURITY;
ALTER TABLE kanji_reference FORCE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE kanji_reference FROM PUBLIC;
REVOKE ALL PRIVILEGES ON TABLE kanji_reference FROM anon, authenticated;
GRANT SELECT ON TABLE kanji_reference TO jlt_runtime;

DROP POLICY IF EXISTS kanji_reference_runtime_select ON kanji_reference;
CREATE POLICY kanji_reference_runtime_select
  ON kanji_reference
  FOR SELECT
  TO jlt_runtime
  USING (true);

DROP TRIGGER IF EXISTS trg_kanji_reference_updated_at ON kanji_reference;
CREATE TRIGGER trg_kanji_reference_updated_at
  BEFORE UPDATE ON kanji_reference
  FOR EACH ROW EXECUTE FUNCTION jlt_set_updated_at();
