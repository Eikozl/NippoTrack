-- JMdict global reference data (Context-Aware Vocabulary Intelligence, CA-B1).
--
-- Snapshot-versioned, immutable-per-snapshot reference storage. Each import
-- writes a NEW source_id; rows are keyed (source_id, ent_seq) so a previous
-- snapshot is never mutated. Activation/rollback only flips the singleton
-- pointer in jmdict_active_snapshot. No tombstones: absence of ent_seq in a
-- new snapshot represents upstream removal.
--
-- No user_id on any table. No user table may FK into these tables.
-- Runtime (jlt_runtime) has SELECT only. Import/activate/prune use the
-- separate migration/admin connection and are never available to runtime.
--
-- Role-guard note: the anon/authenticated REVOKEs below are conditional
-- (002 idiom) rather than bare (006 idiom) so this migration also applies on
-- role-less local databases; on Supabase the roles exist and are revoked.

CREATE TABLE IF NOT EXISTS jmdict_sources (
  source_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_name text NOT NULL DEFAULT 'JMdict',
  file_date date NOT NULL,
  converter text NOT NULL DEFAULT 'jmdict-simplified',
  converter_version text NOT NULL,
  dict_revisions text[] NOT NULL DEFAULT ARRAY[]::text[],
  ent_count integer,
  sha256 char(64) NOT NULL,
  sha256_verified boolean NOT NULL DEFAULT false,
  importer_version text NOT NULL,
  status text NOT NULL DEFAULT 'importing',
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  activated_at timestamptz,
  CONSTRAINT chk_jmdict_sources_status CHECK (status IN ('importing', 'validating', 'ready', 'failed')),
  CONSTRAINT chk_jmdict_sources_sha256 CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  CONSTRAINT uq_jmdict_sources_snapshot UNIQUE (source_name, file_date, converter, converter_version, sha256)
);

CREATE TABLE IF NOT EXISTS jmdict_active_snapshot (
  singleton integer PRIMARY KEY,
  source_id bigint REFERENCES jmdict_sources (source_id) ON DELETE RESTRICT,
  switched_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_jmdict_active_snapshot_singleton CHECK (singleton = 1)
);

-- Seed BEFORE row-level security is forced below: FORCE RLS applies to the
-- table owner as well, so this row must exist before policies take effect.
INSERT INTO jmdict_active_snapshot (singleton, source_id)
VALUES (1, NULL)
ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS jmdict_entries (
  source_id bigint NOT NULL REFERENCES jmdict_sources (source_id) ON DELETE RESTRICT,
  ent_seq bigint NOT NULL,
  doc jsonb NOT NULL,
  pos_summary text[] NOT NULL DEFAULT ARRAY[]::text[],
  is_common boolean NOT NULL DEFAULT false,
  checksum char(64) NOT NULL,
  PRIMARY KEY (source_id, ent_seq),
  CONSTRAINT chk_jmdict_entries_ent_seq CHECK (ent_seq > 0),
  CONSTRAINT chk_jmdict_entries_checksum CHECK (checksum ~ '^[0-9a-f]{64}$')
);

CREATE TABLE IF NOT EXISTS jmdict_forms (
  source_id bigint NOT NULL,
  entry_id bigint NOT NULL,
  surface text NOT NULL,
  normalized text NOT NULL,
  kind text NOT NULL,
  restr text[] NOT NULL DEFAULT ARRAY[]::text[],
  is_common boolean NOT NULL DEFAULT false,
  nokanji boolean NOT NULL DEFAULT false,
  PRIMARY KEY (source_id, entry_id, kind, surface),
  CONSTRAINT fk_jmdict_forms_entry FOREIGN KEY (source_id, entry_id)
    REFERENCES jmdict_entries (source_id, ent_seq) ON DELETE CASCADE,
  CONSTRAINT chk_jmdict_forms_kind CHECK (kind IN ('keb', 'reb')),
  CONSTRAINT chk_jmdict_forms_surface CHECK (surface <> '' AND normalized <> '')
);

CREATE INDEX IF NOT EXISTS idx_jmdict_forms_lookup ON jmdict_forms (source_id, normalized);
CREATE INDEX IF NOT EXISTS idx_jmdict_forms_entry ON jmdict_forms (source_id, entry_id);

CREATE TABLE IF NOT EXISTS jmdict_senses (
  source_id bigint NOT NULL,
  entry_id bigint NOT NULL,
  sense_no integer NOT NULL,
  pos text[] NOT NULL DEFAULT ARRAY[]::text[],
  gloss_en text[] NOT NULL DEFAULT ARRAY[]::text[],
  stagk text[] NOT NULL DEFAULT ARRAY[]::text[],
  stagr text[] NOT NULL DEFAULT ARRAY[]::text[],
  PRIMARY KEY (source_id, entry_id, sense_no),
  CONSTRAINT fk_jmdict_senses_entry FOREIGN KEY (source_id, entry_id)
    REFERENCES jmdict_entries (source_id, ent_seq) ON DELETE CASCADE,
  CONSTRAINT chk_jmdict_senses_sense_no CHECK (sense_no > 0)
);

CREATE INDEX IF NOT EXISTS idx_jmdict_senses_entry ON jmdict_senses (source_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_jmdict_senses_pos ON jmdict_senses USING GIN (pos);

DO $$
DECLARE
  reference_table text;
  api_role text;
BEGIN
  FOREACH reference_table IN ARRAY ARRAY[
    'jmdict_sources', 'jmdict_active_snapshot', 'jmdict_entries',
    'jmdict_forms', 'jmdict_senses'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', reference_table);
    EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', reference_table);
    EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM PUBLIC', reference_table);
    FOREACH api_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
      IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = api_role) THEN
        EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM %I', reference_table, api_role);
      END IF;
    END LOOP;
    EXECUTE format('GRANT SELECT ON TABLE public.%I TO jlt_runtime', reference_table);
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', reference_table || '_runtime_select', reference_table);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I FOR SELECT TO jlt_runtime USING (true)',
      reference_table || '_runtime_select', reference_table
    );
  END LOOP;
END $$;
