-- JLT PostgreSQL baseline. Schema only: intentionally contains no MariaDB data.
-- This is an independent migration stream; do not apply it to MariaDB.

CREATE OR REPLACE FUNCTION jlt_set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

CREATE TABLE vocabulary (
  id_vocabulary integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word varchar(100) NOT NULL, reading varchar(150), meaning text NOT NULL,
  jlpt_level varchar(2), status varchar(20) NOT NULL DEFAULT 'New', notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_vocabulary_jlpt CHECK (jlpt_level IN ('N5','N4','N3','N2','N1') OR jlpt_level IS NULL),
  CONSTRAINT chk_vocabulary_status CHECK (status IN ('New','Learning','Familiar','Mastered'))
);
CREATE TABLE kanji (
  id_kanji integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  character_kanji varchar(4) NOT NULL UNIQUE, meaning varchar(255) NOT NULL, onyomi varchar(255), kunyomi varchar(255),
  jlpt_level varchar(2), status varchar(20) NOT NULL DEFAULT 'New', notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_kanji_jlpt CHECK (jlpt_level IN ('N5','N4','N3','N2','N1') OR jlpt_level IS NULL),
  CONSTRAINT chk_kanji_status CHECK (status IN ('New','Learning','Familiar','Mastered'))
);
CREATE TABLE grammar_points (
  id_grammar integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grammar_point varchar(100) NOT NULL UNIQUE, meaning varchar(255) NOT NULL, structure text, example text,
  jlpt_level varchar(2), status varchar(20) NOT NULL DEFAULT 'New', notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_grammar_jlpt CHECK (jlpt_level IN ('N5','N4','N3','N2','N1') OR jlpt_level IS NULL),
  CONSTRAINT chk_grammar_status CHECK (status IN ('New','Learning','Familiar','Mastered'))
);
CREATE TABLE study_sessions (
  id_session integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_date date NOT NULL, duration_minutes integer NOT NULL, category varchar(20) NOT NULL, resource varchar(255), notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_sessions_duration CHECK (duration_minutes > 0),
  CONSTRAINT chk_sessions_category CHECK (category IN ('Grammar','Vocabulary','Kanji','Reading','Listening','Speaking','Writing','Mixed'))
);
CREATE TABLE kanji_vocabulary (
  id_kanji integer NOT NULL REFERENCES kanji (id_kanji) ON DELETE CASCADE,
  id_vocabulary integer NOT NULL REFERENCES vocabulary (id_vocabulary) ON DELETE CASCADE,
  PRIMARY KEY (id_kanji, id_vocabulary)
);
CREATE TABLE session_grammar (
  id_session integer NOT NULL REFERENCES study_sessions (id_session) ON DELETE CASCADE,
  id_grammar integer NOT NULL REFERENCES grammar_points (id_grammar) ON DELETE CASCADE,
  PRIMARY KEY (id_session, id_grammar)
);
CREATE TABLE session_kanji (
  id_session integer NOT NULL REFERENCES study_sessions (id_session) ON DELETE CASCADE,
  id_kanji integer NOT NULL REFERENCES kanji (id_kanji) ON DELETE CASCADE,
  PRIMARY KEY (id_session, id_kanji)
);
CREATE TABLE session_vocabulary (
  id_session integer NOT NULL REFERENCES study_sessions (id_session) ON DELETE CASCADE,
  id_vocabulary integer NOT NULL REFERENCES vocabulary (id_vocabulary) ON DELETE CASCADE,
  PRIMARY KEY (id_session, id_vocabulary)
);
CREATE TABLE session_writings (
  id_session_writing integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_session integer NOT NULL UNIQUE REFERENCES study_sessions (id_session) ON DELETE CASCADE,
  title varchar(150), content text NOT NULL, notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE usage_examples (
  id_usage_example integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_vocabulary integer NOT NULL REFERENCES vocabulary (id_vocabulary) ON DELETE CASCADE,
  sentence text NOT NULL, translation text, notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE goals (
  id_goal integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(120) NOT NULL, goal_type varchar(30) NOT NULL, target_value integer NOT NULL, period_type varchar(20) NOT NULL,
  target_jlpt_level varchar(2), target_status varchar(20), start_date date NOT NULL, due_date date, is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_goals_type CHECK (goal_type IN ('study_minutes','vocabulary_count','kanji_count','grammar_count')),
  CONSTRAINT chk_goals_target_value CHECK (target_value > 0),
  CONSTRAINT chk_goals_period CHECK (period_type IN ('weekly','cumulative','by_deadline')),
  CONSTRAINT chk_goals_jlpt CHECK (target_jlpt_level IN ('N5','N4','N3','N2','N1') OR target_jlpt_level IS NULL),
  CONSTRAINT chk_goals_status CHECK (target_status IN ('New','Learning','Familiar','Mastered') OR target_status IS NULL),
  CONSTRAINT chk_goals_dates CHECK (due_date IS NULL OR due_date >= start_date)
);
CREATE TABLE content_entries (
  id_content_entry integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(255) NOT NULL, content_type varchar(20) NOT NULL, content_date date NOT NULL, perceived_difficulty smallint,
  comprehension_percent smallint, new_words_count integer, notes text,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_content_entries_type CHECK (content_type IN ('Anime','Manga','Book','Article','YouTube','Podcast','Game','Conversation')),
  CONSTRAINT chk_content_entries_difficulty CHECK (perceived_difficulty BETWEEN 1 AND 5 OR perceived_difficulty IS NULL),
  CONSTRAINT chk_content_entries_comprehension CHECK (comprehension_percent BETWEEN 0 AND 100 OR comprehension_percent IS NULL),
  CONSTRAINT chk_content_entries_words CHECK (new_words_count >= 0 OR new_words_count IS NULL)
);
CREATE TABLE content_entry_sessions (
  id_content_entry integer NOT NULL REFERENCES content_entries (id_content_entry) ON DELETE CASCADE,
  id_session integer NOT NULL REFERENCES study_sessions (id_session) ON DELETE CASCADE,
  PRIMARY KEY (id_content_entry, id_session)
);
CREATE TABLE notes (
  id_note integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(150), body text NOT NULL, category varchar(20) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_notes_category CHECK (category IN ('Grammar','Vocabulary','JapaneseQuestion','Correction','Resource','General'))
);
CREATE TABLE note_study_sessions (id_note integer NOT NULL REFERENCES notes (id_note) ON DELETE CASCADE, id_session integer NOT NULL REFERENCES study_sessions (id_session) ON DELETE CASCADE, PRIMARY KEY (id_note,id_session));
CREATE TABLE note_vocabulary (id_note integer NOT NULL REFERENCES notes (id_note) ON DELETE CASCADE, id_vocabulary integer NOT NULL REFERENCES vocabulary (id_vocabulary) ON DELETE CASCADE, PRIMARY KEY (id_note,id_vocabulary));
CREATE TABLE note_kanji (id_note integer NOT NULL REFERENCES notes (id_note) ON DELETE CASCADE, id_kanji integer NOT NULL REFERENCES kanji (id_kanji) ON DELETE CASCADE, PRIMARY KEY (id_note,id_kanji));
CREATE TABLE note_grammar (id_note integer NOT NULL REFERENCES notes (id_note) ON DELETE CASCADE, id_grammar integer NOT NULL REFERENCES grammar_points (id_grammar) ON DELETE CASCADE, PRIMARY KEY (id_note,id_grammar));
CREATE TABLE tags (
  id_tag integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(60) NOT NULL, normalized_name varchar(60) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE tag_study_sessions (id_tag integer NOT NULL REFERENCES tags (id_tag) ON DELETE CASCADE, id_session integer NOT NULL REFERENCES study_sessions (id_session) ON DELETE CASCADE, PRIMARY KEY (id_tag,id_session));
CREATE TABLE tag_vocabulary (id_tag integer NOT NULL REFERENCES tags (id_tag) ON DELETE CASCADE, id_vocabulary integer NOT NULL REFERENCES vocabulary (id_vocabulary) ON DELETE CASCADE, PRIMARY KEY (id_tag,id_vocabulary));
CREATE TABLE tag_kanji (id_tag integer NOT NULL REFERENCES tags (id_tag) ON DELETE CASCADE, id_kanji integer NOT NULL REFERENCES kanji (id_kanji) ON DELETE CASCADE, PRIMARY KEY (id_tag,id_kanji));
CREATE TABLE tag_grammar (id_tag integer NOT NULL REFERENCES tags (id_tag) ON DELETE CASCADE, id_grammar integer NOT NULL REFERENCES grammar_points (id_grammar) ON DELETE CASCADE, PRIMARY KEY (id_tag,id_grammar));
CREATE TABLE review_items (
  id_review_item integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_vocabulary integer UNIQUE REFERENCES vocabulary (id_vocabulary) ON DELETE CASCADE,
  id_kanji integer UNIQUE REFERENCES kanji (id_kanji) ON DELETE CASCADE,
  id_grammar integer UNIQUE REFERENCES grammar_points (id_grammar) ON DELETE CASCADE,
  due_on date NOT NULL, interval_days smallint NOT NULL DEFAULT 0, last_reviewed_at timestamptz, last_result varchar(20),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_review_items_one_target CHECK (((id_vocabulary IS NOT NULL)::integer + (id_kanji IS NOT NULL)::integer + (id_grammar IS NOT NULL)::integer) = 1),
  CONSTRAINT chk_review_items_interval CHECK (interval_days >= 0)
);
CREATE TABLE review_events (
  id_review_event integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_review_item integer NOT NULL REFERENCES review_items (id_review_item) ON DELETE CASCADE,
  reviewed_at timestamptz NOT NULL, result varchar(20) NOT NULL, previous_interval_days smallint NOT NULL, next_interval_days smallint NOT NULL,
  CONSTRAINT chk_review_events_previous_interval CHECK (previous_interval_days >= 0),
  CONSTRAINT chk_review_events_next_interval CHECK (next_interval_days >= 0)
);

