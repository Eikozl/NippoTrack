// Generates the lazy KanjiVG availability index from the vendored canonical
// filenames. Run after changing client/public/stroke/kanji.
'use strict';

const { readdir, writeFile } = require('node:fs/promises');
const { join } = require('node:path');

const repoRoot = join(__dirname, '..');
const assetDirectory = join(repoRoot, 'client', 'public', 'stroke', 'kanji');
const outputFile = join(repoRoot, 'client', 'src', 'strokeAssetIndex.js');
const filenamePattern = /^([0-9a-f]{5})\.svg$/;

async function main() {
  const codePoints = (await readdir(assetDirectory))
    .map((filename) => filenamePattern.exec(filename))
    .filter(Boolean)
    .map((match) => Number.parseInt(match[1], 16))
    .sort((left, right) => left - right);

  if (!codePoints.length || new Set(codePoints).size !== codePoints.length) {
    throw new Error('Stroke asset filenames must be unique canonical five-digit hexadecimal SVGs.');
  }

  const source = `// Generated by scripts/generate-stroke-asset-index.cjs from local KanjiVG assets.\n`
    + `// Keep this module lazy: strokeOrder.js is dynamically imported by both Kanji views.\n`
    + `export const strokeAssetCodePoints = Uint32Array.from([${codePoints.join(',')}]);\n\n`
    + `export function hasStrokeAssetCodePoint(codePoint) {\n`
    + `  let lower = 0;\n`
    + `  let upper = strokeAssetCodePoints.length - 1;\n`
    + `  while (lower <= upper) {\n`
    + `    const middle = lower + ((upper - lower) >> 1);\n`
    + `    const candidate = strokeAssetCodePoints[middle];\n`
    + `    if (candidate === codePoint) return true;\n`
    + `    if (candidate < codePoint) lower = middle + 1;\n`
    + `    else upper = middle - 1;\n`
    + `  }\n`
    + `  return false;\n`
    + `}\n`;

  await writeFile(outputFile, source, 'utf8');
  console.log(`Wrote ${codePoints.length} KanjiVG code points to ${outputFile}.`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
